import { expect, test } from '@playwright/test'
import { admin, einrichten, taste } from './bedienung'

test('bestätigt eine externe PayPal-Zahlung und korrigiert die Statistik beim Storno', async ({ page }) => {
  await einrichten(page)
  await taste(page, /^Glas \/ Tasse/).click()
  await taste(page, 'Zur Zahlung').click()
  await expect(page.locator('.geldwahl button').last()).toHaveText('PayPal')
  await taste(page, 'PayPal').click()
  await taste(page, 'Abbrechen').click()
  await taste(page, 'PayPal').click()
  const dialog = page.getByRole('dialog', { name: 'PayPal-Zahlung bestätigen' })
  await expect(dialog).toContainText('5,00 €')
  await dialog.getByRole('button', { name: 'Vorgang abschließen' }).click()
  await expect(page.getByRole('dialog', { name: 'Vorgang 1 gebucht.' })).toBeVisible()
  await taste(page, 'Zur letzten Bestellung').click()
  await expect(page.getByText('Per PayPal bezahlt')).toBeVisible()
  await taste(page, 'Zurück zur Bestellung').click()
  await admin(page)
  const paypal = page.locator('dt').filter({ hasText: 'PayPal' }).locator('+ dd')
  await expect(paypal).toHaveText('5,00 €')
  await expect(page.locator('dt').filter({ hasText: 'Bar (inkl.' }).locator('+ dd')).toHaveText('0,00 €')
  await taste(page, 'Letzten Verkauf stornieren').click()
  await taste(page, 'Storno bestätigen').click()
  await expect(paypal).toHaveText('0,00 €')
})

test('berechnet Flasche mit vier Gläsern und hält den Unterzahlungshinweis bei 2, sichtbar', async ({ page }) => {
  await einrichten(page)
  await taste(page, /^Wein Flasche/).click()
  const glas = taste(page, /^Glas \/ Tasse 5,00 € Pfand/)
  for (let i = 0; i < 4; i++) await glas.click()
  await expect(page.locator('.bestellsumme')).toHaveText('+ 38,00 €')
  await taste(page, 'Zur Zahlung').click()
  const position = page.locator('.zahlungsartikel').filter({ hasText: 'Glas / Tasse' })
  await expect(position.locator('.positionsmenge')).toHaveText('4×')
  await expect(position.locator('.glas-symbol')).toBeVisible()
  await expect(page.locator('.zahlungsartikel').filter({ hasText: 'Wein' })).toContainText('🍾')
  await taste(page, 'Anderer Betrag').click()
  const dialog = page.getByRole('dialog')
  for (const taste of '2,99') {
    await dialog.getByRole('button', { name: taste, exact: true }).click()
    await expect(dialog).toContainText('Der gegebene Betrag reicht nicht aus.')
    await expect(dialog.getByRole('button', { name: 'Rückgeld anzeigen' })).toBeDisabled()
  }
})

test('zeigt Rückgeld im Dialog und die letzte bezahlte Bestellung ohne erneute Buchung', async ({ page }, info) => {
  await page.setViewportSize({ width: 1024, height: 600 })
  await einrichten(page)
  await expect(taste(page, 'Zur letzten Bestellung')).toBeDisabled()
  await taste(page, /^Glühwein rot \d/).click()
  await taste(page, 'Zur Zahlung').click()
  await expect(page.locator('.zahlungsartikel.gluehwein-rot')).toHaveCSS('background-color', 'rgb(121, 44, 68)')
  await taste(page, '10 €').click()
  const dialog = page.getByRole('dialog', { name: 'Rückgeld', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button')).toHaveText(['Vorgang abschließen', 'Bargeld ändern', 'Zurück zur Bestellung'])
  await expect(dialog).toContainText('1,00 € Rückgeld')
  const abschluss = dialog.getByRole('button', { name: 'Vorgang abschließen' })
  const zurueck = dialog.getByRole('button', { name: 'Zurück zur Bestellung' })
  expect((await abschluss.boundingBox())!.height).toBeGreaterThan((await zurueck.boundingBox())!.height)
  if (info.project.name === 'WebKit') await page.screenshot({ path: info.outputPath('rueckgeld-popup.png') })
  await zurueck.click()
  await expect(page.locator('.bestellsumme')).toHaveText('+ 9,00 €')
  await taste(page, 'Zur Zahlung').click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await taste(page, 'Passend').evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
  const erfolg = page.getByRole('dialog', { name: 'Vorgang 1 gebucht.' })
  await expect(erfolg).toBeVisible()
  await expect(erfolg).toHaveCSS('animation-name', 'none')
  await expect(erfolg).toHaveCSS('animation-duration', '0.8s')
  await expect(dialog).toHaveCount(0)
  await expect(taste(page, 'Zur Zahlung')).toBeDisabled()

  // Eine neue Bestellung bleibt beim Rückblick erhalten.
  await taste(page, /^Glühwein weiß \d/).click()
  await taste(page, 'Zur letzten Bestellung').click()
  await expect(page.getByRole('heading', { name: 'Letzte Bestellung · Vorgang 1' })).toBeVisible()
  await expect(page.locator('.zahlungszusammenfassung')).toContainText('Glühwein rot')
  await expect(page.getByText('9,00 €', { exact: true })).toBeVisible()
  await expect(taste(page, 'Vorgang abschließen')).toHaveCount(0)
  await taste(page, 'Zurück zur Bestellung').click()
  await expect(page.locator('.bestellpositionen')).toContainText('Glühwein weiß')
  await taste(page, 'Zur Zahlung').click()
  await taste(page, '20 €').click()
  await expect(dialog).toContainText('11,00 € Rückgeld')
  await abschluss.click()
  await expect(page.getByRole('dialog', { name: 'Vorgang 2 gebucht.' })).toHaveCSS('animation-duration', '0.4s')
  await page.reload()
  await taste(page, 'Zur letzten Bestellung').click()
  await expect(page.getByRole('heading', { name: 'Letzte Bestellung · Vorgang 2' })).toBeVisible()
  await expect(page.locator('.zahlungszusammenfassung')).toContainText('Glühwein weiß')
  await expect(page.getByText('11,00 € Rückgeld')).toBeVisible()
})

test('korrigiert unzureichendes und freies Bargeld im Zahlungsdialog', async ({ page }) => {
  await einrichten(page)
  await taste(page, /^Glühwein rot \d/).click()
  await taste(page, 'Zur Zahlung').click()
  await taste(page, '5 €').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('reicht nicht aus')
  await expect(dialog.getByRole('button', { name: 'Vorgang abschließen' })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Bargeld ändern' }).click()
  await taste(page, 'Anderer Betrag').click()
  const uebernehmen = dialog.getByRole('button', { name: 'Rückgeld anzeigen' })
  await expect(uebernehmen).toBeDisabled()
  await page.keyboard.type('5')
  await expect(uebernehmen).toBeDisabled()
  await taste(page, 'Abbrechen').click()
  await expect(dialog).toHaveCount(0)
  await taste(page, 'Anderer Betrag').click()
  await page.keyboard.type('12,503')
  await expect(page.getByLabel('Eingegebener Betrag')).toHaveText('12,50 €')
  await uebernehmen.click()
  await expect(dialog).toContainText('3,50 € Rückgeld')
  await taste(page, 'Bargeld ändern').click()
  await expect(page.getByLabel('Eingegebener Betrag')).toHaveText('12,50 €')
  for (let i = 0; i < 5; i++) await page.keyboard.press('Backspace')
  await page.keyboard.type('20')
  await uebernehmen.click()
  await expect(dialog).toContainText('11,00 € Rückgeld')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
